"""docqa — CLI для вопросов по папке с документами (Ф4-08, чек-поинт фазы 4).

Собран из ragkit: tools (реестр, диспетчер, ToolLoop), conversation (история, обрезка,
бюджет), streaming (поток с тремя таймаутами и вызовами инструментов), prompts (версия),
cost (порог цены до отправки).

Что пришлось дописать в ragkit — и почему модули были спроектированы не под эту задачу:
- streaming не знал об инструментах: протокол клиента без tools=, а сборщик потока брал
  только текст. Вызов в потоковом режиме терялся бы молча, и ход выглядел бы как пустой
  ответ. Добавлены StreamToolCall, Envelope.tool_calls и astream_tool_chat.
- tools.run_tools — цикл целиком и без потока: «запрос → весь ответ → вызовы». Взять из него
  одну итерацию (запрет повтора, вызов, порядок результатов) было нельзя, пришлось бы
  копировать. Вынесено в ToolLoop и assistant_message; run_tools теперь на них же.
- conversation.Conversation записывал только пару «вопрос — ответ» и сам делал запрос.
  Ход, где запросов несколько и между ними результаты инструментов, записать было нечем.
  Добавлен commit_turn: цикл живёт снаружи, а ход попадает в историю законченным и целиком.
- cost.CostGuard.chat не умеет ни поток, ни tools; сессия зовёт CostGuard.check перед
  каждым обращением, а CostGuard.chat не используется.

Присест 2 (таблица отказов):
- CostGuard считал вход только сам, оценкой. А у сессии со второго обращения есть число
  точнее — prompt_eval_count прошлого обращения. Добавлены CostGuard.check_tokens (порог
  по известному числу) и conversation.CalibratedCount (факт за префикс + оценка остатка);
  им же считает Conversation. Насколько это точнее — в --debug и журнале (estimate_error).
- tools: вызов, написанный текстом, раньше распознавали только тесты урока Ф4-06. Вынесены
  looks_like_raw_call, parse_raw_tool_calls и UnparsedToolCallError. ToolResult получил
  detail — исходную ошибку для журнала: content для модели урезан белым списком, и без
  detail в логе не было бы пути и типа исключения.

Присест 3:
- structured.ask_structured синхронный, а сессия — асинхронная. Добавлен aask_structured:
  та же схема в format=, тот же разбор и три отказа; возвращает и ответ сервера — на нём
  счётчики токенов для цены и окна.
- quality.script_mess — проверка смеси письменностей из Ф4-01, вынесена из урока, чтобы
  её звал код продукта, а не только скрипт замера.

Своё у docqa: guards (карантин строк, вырезание адресов, придержка вызова текстом), events
(журнал JSON), faults (инъектор отказов для --fault), answer (итог-объект и проверки), notes
(save_note за подтверждением).
"""
